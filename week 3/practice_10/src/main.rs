fn main() {
    let a: i32 = 10;
    let b: i32 = 6;

    let sum = a + b;
    let difference = a - b;
    let product = a * b;
    let quotient = a / b;
    let remainder = a % b;

    println!("sum: {}", sum); //additiom
    println!("difference: {}", difference); //subtraction
    println!("product: {}", product); // multiplication
    println!("quotient: {}", quotient); //division
    println!("remainder: {}", remainder); //remainder
}
